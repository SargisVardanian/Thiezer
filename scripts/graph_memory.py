def duplicate_claim_exists(graph: dict[str, Any], claim: dict[str, Any]) -> bool:
    c_hash = str(claim.get("claim_hash") or claim_hash(claim))
    for relation in graph.get("relations", []):
        if str(relation.get("claim_hash") or "") == c_hash:
            return True
    for event in graph.get("event_nodes", []):
        if str(event.get("claim_hash") or "") == c_hash:
            return True
    return False


def no_self_citation(source_links: list[dict[str, Any]], publication_ledger: list[dict[str, Any]] | None = None) -> bool:
    publication_ledger = publication_ledger if publication_ledger is not None else load_publication_ledger(limit=800)
    published_urls = {
        str(url).strip()
        for row in publication_ledger
        if isinstance(row, dict)
        for url in (row.get("source_links", []) or [])
        if str(url).strip()
    }
    for row in source_links:
        if not isinstance(row, dict):
            continue
        url = str(row.get("url") or "").strip()
        if url and url in published_urls:
            return False
    return True


def confidence_decay(confidence: float, days_since_checked: float, *, half_life_days: float = 60.0) -> float:
    if confidence <= 0:
        return 0.0
    decay = 0.5 ** max(0.0, days_since_checked / max(1.0, half_life_days))
    return round(confidence * decay, 3)


def novelty_gate(claim: dict[str, Any], graph: dict[str, Any]) -> bool:
    return not duplicate_claim_exists(graph, claim)


def promote_or_reject_proposal(proposal: dict[str, Any], graph: dict[str, Any]) -> str:
    if not proposal.get("claims"):
        return "rejected"
    source_links = [item for item in proposal.get("evidence_refs", []) if isinstance(item, str)]
    if source_links and not no_self_citation([source_link_record(url) for url in source_links]):
        return "disputed"
    if any(duplicate_claim_exists(graph, claim) for claim in proposal.get("claims", []) if isinstance(claim, dict)):
        return "disputed"
    if any(float(claim.get("source_independence_score", 0.0) or 0.0) < 0.5 for claim in proposal.get("claims", []) if isinstance(claim, dict)):
        return "pending"
    if any(str(claim.get("layer") or "episodic") == "durable" for claim in proposal.get("claims", []) if isinstance(claim, dict)):
        return "accepted"
    return "accepted"


