    if not entity_ids and story:
        entity_ids = [str(item).strip() for item in story.get("actors_detected", []) if str(item).strip()]
    dossiers = [dossier_bundle(graph, entity_id) for entity_id in entity_ids[:8]]
    entity_cards = [dossier.get("entity_card") for dossier in dossiers if isinstance(dossier, dict) and dossier.get("entity_card")]
